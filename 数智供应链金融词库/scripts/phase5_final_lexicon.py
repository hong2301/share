def main():
    print("构建最终词库...")
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "词库汇总"
    ws.append(["一级维度", "二级维度", "关键词示例", "原始关键词个数", "归一化关键词个数"])

    total_raw = 0
    total_norm = 0
    detail_rows = []

    for dim, subs in FINAL_LEXICON.items():
        for sub, word_groups in subs.items():
            raw_words = []  # 所有原始词（含变体）
            norm_words = []  # 归一化标准词
            for std, variants in word_groups.items():
                norm_words.append(std)
                raw_words.extend(variants)
                raw_words.extend(std if std not in variants else [])
            raw_words = list(dict.fromkeys(raw_words))  # 去重保序
            norm_words = list(dict.fromkeys(norm_words))

            raw_count = len(raw_words)
            norm_count = len(norm_words)
            total_raw += raw_count
            total_norm += norm_count

            ws.append([dim, sub, "、".join(raw_words), raw_count, norm_count])
            detail_rows.append((dim, sub, raw_count, norm_count))

    ws.append(["合计", "", "", total_raw, total_norm])

    # 设置列宽
    ws.column_dimensions['A'].width = 24
    ws.column_dimensions['B'].width = 26
    ws.column_dimensions['C'].width = 100
    ws.column_dimensions['D'].width = 16
    ws.column_dimensions['E'].width = 18

    wb.save(FINAL_XLSX)
    print(f"✅ 已生成: {FINAL_XLSX}")
    print(f"   原始关键词: {total_raw} 个")
    print(f"   归一化关键词: {total_norm} 个")
    print(f"   归一化率: {(1 - total_norm/total_raw)*100:.1f}%")

    print("\n=== 词库概览 ===")
    for dim, sub, raw, norm in detail_rows:
        print(f"  {sub}: 原始{raw} → 归一化{norm}")


if __name__ == "__main__":
    main()
